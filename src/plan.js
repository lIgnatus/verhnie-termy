export const SPRUCES = [];
const row = (pts, step, jitter = 0) => {
  for (let i = 0; i + 1 < pts.length; i++) {
    const [ax, ay] = pts[i], [bx, by] = pts[i + 1], l = Math.hypot(bx - ax, by - ay), n = Math.max(1, Math.round(l / step));
    for (let k = 0; k <= n; k++) SPRUCES.push([ax + ((bx - ax) * k) / n + Math.sin(k * 12.9 + i) * jitter, ay + ((by - ay) * k) / n + Math.cos(k * 7.7 + i) * jitter]);
  }
};
